def mocks(slots=SLOTS_SENTINEL, book=BOOK_SENTINEL):
    if book.get("booking_ref"):  # same shape as the real function's success response
        book = dict(book, booking_ref_spoken=" ".join(c for c in book["booking_ref"] if c.isalnum()))
    return [{"name": "check_visit_slots", "mock": True, "response": slots},
            {"name": "book_site_visit", "mock": True, "response": book}]


CALLER_RULES = """Rules:
- Never tell the agent what to do. Never correct it. Never hint at the right answer.
- Only give information when the agent asks for it. Never volunteer extra details unless your script says so.
- Your name is {name}. Never use the agent's name or any other name as your own.
- Never say or imply this is a test, a simulation or an evaluation.
- Do not say goodbye or end the call yourself unless your script says so. When the agent wraps up, reply briefly ("{ok}") and wait. If the agent repeats itself 3 times without progress, say "{exit}" and stop talking."""


def rules(name, ok="Theek hai", exit_line="Achha theek hai, baad mein baat karte hain"):
    return CALLER_RULES.format(name=name, ok=ok, exit=exit_line)


